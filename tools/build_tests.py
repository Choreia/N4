#!/usr/bin/env python3
"""Build weekly mock tests for the Worker bundle.

worker/tests_src/tests.json (manifest) + part files (authoring format: options[0] = correct, see SPEC.md)
  -> worker/tests_built/<id>.json (options shuffled with a fixed seed, question ids, answer key, explanations)
  -> worker/tests_built/index.js  (export const TESTS = {...})
Both directories are git-ignored: the public repo must never contain test content or keys.
Tests whose part files are missing are skipped (with a warning) so a partial set still builds.
"""
import json, os, random, sys, hashlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'worker', 'tests_src')
OUT = os.path.join(ROOT, 'worker', 'tests_built')


def match(group, flt):
    return all(str(group.get(k)) == str(v) for k, v in flt.items())


def shuffle(opts, rng):
    idx = list(range(len(opts)))
    rng.shuffle(idx)
    return [opts[i] for i in idx], idx.index(0)


def build(t):
    rng = random.Random(int(hashlib.sha256(t['id'].encode()).hexdigest()[:12], 16))
    key, exp, sec_of = {}, {}, {}
    n = 0
    out_sections = []
    for s in t['sections']:
        groups = []
        for fname, flt in s['from']:
            path = os.path.join(SRC, fname)
            if not os.path.exists(path):
                raise FileNotFoundError(fname)
            data = json.load(open(path, encoding='utf-8'))
            for g in data['groups']:
                if not match(g, flt):
                    continue
                part = g.get('part')
                if s.get('audio'):
                    sets = []
                    for st in g['sets']:
                        qs = []
                        for q in st['questions']:
                            n += 1
                            qid = '%s-%03d' % (t['id'], n)
                            opts, ans = shuffle(q['options'], rng)
                            key[qid], exp[qid], sec_of[qid] = ans, q.get('exp', ''), s['id']
                            qs.append({'id': qid, 'no': n, 'q': q.get('q', ''), 'options': opts, 'spoken': bool(q.get('spoken'))})
                        sets.append({'situation': st.get('situation', ''), 'script': st['script'], 'questions': qs})
                    groups.append({'instr': g.get('instr', ''), 'part': part, 'sets': sets})
                else:
                    qs = []
                    for q in g['questions']:
                        n += 1
                        qid = '%s-%03d' % (t['id'], n)
                        opts, ans = shuffle(q['options'], rng)
                        key[qid], exp[qid], sec_of[qid] = ans, q.get('exp', ''), s['id']
                        qs.append({'id': qid, 'no': n, 'q': q['q'], 'options': opts})
                    groups.append({'instr': g.get('instr', ''), 'part': part, 'passage': g.get('passage', ''), 'questions': qs})
        sec = {k: s[k] for k in ('id', 'title', 'minutes', 'optLabels') if k in s}
        sec.update({'audio': bool(s.get('audio')), 'pause': s.get('pause'), 'groups': groups})
        out_sections.append(sec)
    built = {k: t[k] for k in ('id', 'course', 'level', 'title', 'scoring', 'scoreGroups') if k in t}
    built.update({'passTotal': t.get('passTotal', 0), 'sections': out_sections, 'key': key, 'exp': exp, 'secOf': sec_of})
    return built


def main():
    os.makedirs(OUT, exist_ok=True)
    manifest = json.load(open(os.path.join(SRC, 'tests.json'), encoding='utf-8'))
    built = []
    for t in manifest:
        try:
            b = build(t)
        except FileNotFoundError as e:
            print('skip %s: missing %s' % (t['id'], e), file=sys.stderr)
            continue
        json.dump(b, open(os.path.join(OUT, b['id'] + '.json'), 'w', encoding='utf-8'), ensure_ascii=False)
        dist = {}
        for v in b['key'].values():
            dist[v] = dist.get(v, 0) + 1
        print('%s: %d questions, answer positions %s' % (b['id'], len(b['key']), dict(sorted(dist.items()))))
        built.append(b['id'])
    lines = ['// generated by tools/build_tests.py — do not edit, do not commit']
    for i, tid in enumerate(built):
        lines.append("import t%d from './%s.json';" % (i, tid))
    lines.append('export const TESTS = {' + ', '.join("'%s': t%d" % (tid, i) for i, tid in enumerate(built)) + '};')
    open(os.path.join(OUT, 'index.js'), 'w').write('\n'.join(lines) + '\n')
    print('index.js: %d tests' % len(built))


if __name__ == '__main__':
    main()
